// Date (ساعت محلی گوشی) → {jy, jm, jd}
export function toJ(date) {
  const d = new Date(date);
  return d2j(g2d(d.getFullYear(), d.getMonth() + 1, d.getDate()));
}
// شمسی → Date ساعت ۰۰:۰۰ همان روز
export function fromJ(jy, jm, jd) {
  const g = d2g(j2d(jy, jm, jd));
  return new Date(g.gy, g.gm - 1, g.gd);
}
export function isLeapJ(jy) { return jalCal(jy).leap === 0; }
export function monthLength(jy, jm) { return jm <= 6 ? 31 : jm <= 11 ? 30 : (isLeapJ(jy) ? 30 : 29); }

// بازه‌ی یک ماه شمسی: [شروع، شروع ماه بعد)
export function monthRange(jy, jm) {
  const start = fromJ(jy, jm, 1);
  const ny = jm === 12 ? jy + 1 : jy, nm = jm === 12 ? 1 : jm + 1;
  return [start, fromJ(ny, nm, 1)];
}
export function prevMonth(jy, jm) { return jm === 1 ? [jy - 1, 12] : [jy, jm - 1]; }
